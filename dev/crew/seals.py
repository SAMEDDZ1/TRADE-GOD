def grid(name):
    rows = [r for r in SEALS[name].strip('\n').split('\n')]
    assert len(rows) == 12 and all(len(r) == 12 for r in rows), (name, [len(r) for r in rows])
    return rows

def runs(rows, chars, scale=2, off=4):
    """merge horizontal runs of matching cells into one SVG path string."""
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < 12:
            if row[x] in chars:
                x0 = x
                while x < 12 and row[x] in chars: x += 1
                X0, X1, Y0, Y1 = off + x0 * scale, off + x * scale, off + y * scale, off + (y + 1) * scale
                out.append('M%d %dH%dV%dH%dZ' % (X0, Y0, X1, Y1, X0))
            else:
                x += 1
    return ' '.join(out)

def svg(name):
    rows = grid(name)
    body = runs(rows, '#o'); hi = runs(rows, 'o')
    s = ('<svg viewBox="0 0 32 32" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true" focusable="false">'
         '<g style="color:color-mix(in srgb, currentColor 28%, black)" transform="translate(1 1)"><path d="' + body + '"/></g>'
         '<path d="' + body + '"/>')
    if hi:
        s += '<g style="color:color-mix(in srgb, currentColor 42%, white)"><path d="' + hi + '"/></g>'
    return s + '</svg>'

